export function getVehicleStatus(vehicle: Vehicle): VehicleStatus {
  return vehicle.status ?? 'Disponible'
}

export function getVehicleBySlug(slug: string): Vehicle | undefined {
  return vehicles.find(v => v.slug === slug)
}

export function getFeaturedVehicles(): Vehicle[] {
  return vehicles.filter(v => v.featured)
}

export function getNewArrivals(): Vehicle[] {
  return vehicles.filter(v => v.newArrival)
}

export function getVehiclesByBrand(brand: string): Vehicle[] {
  return vehicles.filter(v => v.brand.toLowerCase() === brand.toLowerCase())
}

export function getVehiclesByType(type: Vehicle['type']): Vehicle[] {
  return vehicles.filter(v => v.type === type)
}

export function getAllBrands(): string[] {
  return [...new Set(vehicles.map(v => v.brand))].sort()
}

export function getAllTypes(): Vehicle['type'][] {
  return [...new Set(vehicles.map(v => v.type))]
}

/** Cifras calculadas desde el stock real: nunca se escriben a mano. */
export function getCatalogStats() {
  const years = vehicles.map(v => v.year)
  return {
    units: vehicles.length,
    brands: getAllBrands().length,
    newestYear: Math.max(...years),
    oldestYear: Math.min(...years),
  }
}
